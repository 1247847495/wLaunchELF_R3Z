$rxArabic = New-Object System.Text.RegularExpressions.Regex('\b(\d{1,4})\b', [System.Text.RegularExpressions.RegexOptions]::Compiled)
$rxRoman  = New-Object System.Text.RegularExpressions.Regex('\b(XX|XIII|XII|XI|X|IX|VIII|VII|VI|IV|V|III|II)\b(?![-\w])', [System.Text.RegularExpressions.RegexOptions]::Compiled)

#========== 主循环:解析 CSV,翻译,去重 ==========
$result = New-Object 'System.Collections.Generic.SortedDictionary[string,string]'
$total = 0; $hit = 0; $skipped = 0
foreach ($line in [System.IO.File]::ReadLines($csvPath)) {
	if ([string]::IsNullOrWhiteSpace($line)) { continue }
	$total++
	$idx = $line.IndexOf(';')
	if ($idx -lt 1) { continue }
	$serial = $line.Substring(0, $idx)
	$title = $line.Substring($idx + 1)
	$m = $rxSerial.Match($serial)
	if (-not $m.Success) { $skipped++; continue }
	$code = $m.Groups[1].Value + '-' + $m.Groups[2].Value + $m.Groups[3].Value
	if ($result.ContainsKey($code)) { continue }  #同 code 只保留第一条

	$cn = $null
	#第1层:精确短语
	$em = $Ex.Rx.Match($title)
	if ($em.Success) {
		$cn = $Ex.Map[$em.Value.ToLowerInvariant()]
	} else {
		#第2层:系列
		$sm = $Se.Rx.Match($title)
		if ($sm.Success) {
			$s = $Se.Map[$sm.Value.ToLowerInvariant()]
			#副标题:取所有命中里最长的短语(如 Project Zero 2 - Crimson Butterfly
			#同时命中 Zero 与 Crimson Butterfly,应取更具体的后者)
			$u = $null
			$best = 0
			foreach ($mm in $Su.Rx.Matches($title)) {
				if ($mm.Value.Length -gt $best) { $best = $mm.Value.Length; $u = $Su.Map[$mm.Value.ToLowerInvariant()] }
			}
			#序号(阿拉伯优先;副标题存在时仅附加阿拉伯,避免 CVX 的 X 之类误判)
			$num = $null; $roman = $null
			$am = $rxArabic.Match($title)
			if ($am.Success) { $num = ([int]$am.Groups[1].Value).ToString() }
			if ($u) {
				if ($num) { $cn = "$s$num`：$u" } else { $cn = "$s`：$u" }
			} else {
				if (-not $num) {
					$rm = $rxRoman.Match($title)
					if ($rm.Success) { $roman = $rm.Groups[1].Value }
				}
				if ($num) { $cn = "$s$num" }
				elseif ($roman) { $cn = "$s$roman" }
				else { $cn = $s }
			}
		}
	}
	if ($cn) { $result[$code] = $cn; $hit++ }
}

