#========== 构建编译好的正则(按关键词长度降序,保证最长优先;含词边界防误伤) ==========
function Build-Matcher($pairs) {
	$sorted = $pairs | Sort-Object { $_[0].Length } -Descending
	$map = @{}
	foreach ($p in $sorted) { $map[$p[0].ToLowerInvariant()] = $p[1] }
	$alt = ($sorted | ForEach-Object {
		$e = [regex]::Escape($_[0])
		if ($_[0][0]  -match '[A-Za-z0-9]') { $e = '\b' + $e }
		if ($_[-1][-1] -match '[A-Za-z0-9]') { $e = $e + '\b' }
		$e
	}) -join '|'
	$opts = [System.Text.RegularExpressions.RegexOptions]'IgnoreCase, Compiled'
	$rx = New-Object System.Text.RegularExpressions.Regex("(?:$alt)", $opts)
	return @{ Rx = $rx; Map = $map }
}
